def set_text(record: dict, identity: str, said: str) -> None:
    """Change what the application said, in the record's scene and in what the record says it supplied."""
    for holder in (scene_of(record)["elements"], record["application"]["bound_elements"]):
        for item in holder:
            bound = item.get("bound", item)
            if bound.get("identity") == identity:
                bound["text"] = said


def test_a_line_that_says_nothing_is_no_tspan_and_the_lines_after_it_keep_their_places(records, tmp_path):
    record = copy.deepcopy(next(item for item in records if any(e["id"] == "b.editor.body" for e in scene_of(item)["elements"])))
    outs = {}
    for name, said in (("gap", "first\n\nthird\n"), ("full", "first\nsecond\nthird\nfourth")):
        set_text(record, "editor.body", said)
        path = tmp_path / f"{name}.json"
        path.write_text(json.dumps(record))
        result = run_cli("scene", "export", path, "--out", tmp_path / f"{name}.svg")
        assert result.returncode == 0, result.stderr
        text = groups_of(ET.fromstring((tmp_path / f"{name}.svg").read_bytes()))["b.editor.body"].find(f"{SVG}text")
        outs[name] = [(span.text, span.get("x"), span.get("y")) for span in text.findall(f"{SVG}tspan")]
    assert [said for said, _, _ in outs["gap"]] == ["first", "third"]
    assert [place[1:] for place in outs["gap"]] == [outs["full"][0][1:], outs["full"][2][1:]]


def test_a_shadow_filter_never_takes_an_elements_id(records, tmp_path):
    scene = copy.deepcopy(scene_of(next(item for item in records if item["diagnostics"]["visual_preset"] == "night-teal")))
    elevation = next(element["style"]["elevation"] for element in scene["elements"] if element["id"] == "s.list")
    taken = f"elevation-{elevation:g}"
    for element in scene["elements"]:
        if element["id"] == "s.list":
            element["id"] = taken
        if element["parent"] == "s.list":
            element["parent"] = taken
    path = tmp_path / "scene.json"
    path.write_text(json.dumps(scene))
    result = run_cli("scene", "export", path, "--out", tmp_path / "scene.svg")
    assert result.returncode == 0, result.stderr
    root = ET.fromstring((tmp_path / "scene.svg").read_bytes())
    ids = [node.get("id") for node in root.iter() if node.get("id") is not None]
    assert len(ids) == len(set(ids)) and taken in groups_of(root)
    filters = {node.get("id") for node in root.iter(f"{SVG}filter")}
