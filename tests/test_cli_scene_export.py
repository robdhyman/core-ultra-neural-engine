def test_the_difference_from_the_runtime_renderer_is_measured_for_every_record(comparison, dataset, records, exported):
    record = comparison["record"]
    assert record["kind"] == "scene-export-comparison"
    assert "Qt SVG" in record["rasterised_by"]["tool"] and record["rasterised_by"]["qt"]
    assert record["compared_with"] == "runtime renderer"
    assert record["dataset"]["manifest_sha256"] == hashlib.sha256((dataset / "manifest.json").read_bytes()).hexdigest()
    assert [entry["id"] for entry in record["records"]] == [item["id"] for item in records]

    # Judged here: the exported SVG drawn by Qt's SVG module against the
    # dataset's own reference image, which the runtime renderer drew.
    for entry, item in list(zip(record["records"], records))[::7]:
        reference = reference_image(dataset, item)
        drawn = rasterise(exported[item["id"]], reference.shape[1], reference.shape[0])
        difference = np.abs(drawn.astype(np.int16) - reference.astype(np.int16))
        whole = entry["whole"]
        assert whole["mean_absolute_difference"] == pytest.approx(float(difference.mean()), abs=1e-9)
        assert whole["largest_difference"] == int(difference.max())
        assert whole["share_of_pixels_over_16"] == pytest.approx(float((difference.max(axis=2) > 16).mean()), abs=1e-12)
        assert entry["visual_preset"] == item["diagnostics"]["visual_preset"]
        assert entry["pixels"] == [reference.shape[1], reference.shape[0]]


def test_the_difference_is_reported_whole_and_without_text_overall_and_by_visual_preset(comparison, records):
    record = comparison["record"]
    for entry in record["records"]:
        for part in ("whole", "without_text"):
            numbers = entry[part]
            assert 0 <= numbers["mean_absolute_difference"] <= 255
            assert 0 <= numbers["share_of_pixels_over_16"] <= 1
            assert 0 <= numbers["largest_difference"] <= 255
        # Every record says something, and text is most of what differs: without it, less does.
        assert entry["without_text"]["mean_absolute_difference"] < entry["whole"]["mean_absolute_difference"]
    assert set(record["by_visual_preset"]) == PRESETS
    assert sum(group["records"] for group in record["by_visual_preset"].values()) == record["overall"]["records"] == len(records)
    means = [entry["whole"]["mean_absolute_difference"] for entry in record["records"]]
    assert record["overall"]["whole"]["mean_absolute_difference"]["mean"] == pytest.approx(sum(means) / len(means))
    assert record["overall"]["whole"]["mean_absolute_difference"]["largest"] == max(means)
    # The numbers are measurements: the export is not the renderer, and says so.
    assert record["overall"]["whole"]["mean_absolute_difference"]["mean"] > 0
    multiline = [item["id"] for item in records if any("\n" in e["bound"]["text"] for e in scene_of(item)["elements"] if e["type"] == "bound")]
    assert record["records_with_text_on_several_lines"]["ids"] == multiline

    said = comparison["result"].stdout
    assert "Qt SVG" in said and "runtime renderer" in said
    for preset in PRESETS:
        assert preset in said


