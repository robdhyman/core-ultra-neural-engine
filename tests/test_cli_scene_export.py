def run_cli(*args: str | Path, cwd: Path = REPO_ROOT) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "core_ultra", *map(str, args)], capture_output=True, text=True, cwd=cwd, timeout=600
    )


