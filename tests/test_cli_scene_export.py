def test_fill_border_corner_radius_and_opacity_are_the_scenes_style_values(records, exported):
    seen = {"border": 0, "no border": 0, "no fill": 0, "opacity": 0, "radius": 0}
    for record in records:
        groups = groups_of(ET.fromstring(exported[record["id"]]))
        for element in scene_of(record)["elements"]:
            style, box = element["style"], element["box"]
            rect = groups[element["id"]].find(f"{SVG}rect")

            if style["fill"][3] == 0:
                assert rect.get("fill") == "none"
                seen["no fill"] += 1
            else:
                assert rect.get("fill") == hex_of(style["fill"])
                assert float(rect.get("fill-opacity", "1")) == style["fill"][3]

            bordered = style["border_width"] > 0 and style["border_colour"][3] > 0
            # SVG strokes along the middle of an outline; the scene's border lies
            # inside it. The rectangle is therefore drawn half a border in.
            half = style["border_width"] / 2 if bordered else 0.0
            if bordered:
                assert rect.get("stroke") == hex_of(style["border_colour"])
                assert number(rect.get("stroke-width")) == style["border_width"]
                assert float(rect.get("stroke-opacity", "1")) == style["border_colour"][3]
                seen["border"] += 1
            else:
                assert rect.get("stroke") is None and rect.get("stroke-width") is None
                seen["no border"] += 1
            assert number(rect.get("x")) == pytest.approx(box["x"] + half, abs=1e-6)
            assert number(rect.get("y")) == pytest.approx(box["y"] + half, abs=1e-6)
            assert number(rect.get("width")) == pytest.approx(box["width"] - 2 * half, abs=1e-6)
            assert number(rect.get("height")) == pytest.approx(box["height"] - 2 * half, abs=1e-6)

            radius = max(style["corner_radius"] - half, 0.0)
            assert float(rect.get("rx", "0")) == pytest.approx(radius, abs=1e-6)
            assert rect.get("ry") is None or float(rect.get("ry")) == pytest.approx(radius, abs=1e-6)
            seen["radius"] += radius > 0

            # Opacity is the element's own: on its shape and its text, never on
            # the group, which also holds the elements inside it.
            assert groups[element["id"]].get("opacity") is None
            for own in groups[element["id"]].findall("*"):
                if own.tag != f"{SVG}g":
                    assert float(own.get("opacity", "1")) == style["opacity"]
            seen["opacity"] += style["opacity"] < 1
    assert all(seen.values()), seen


def test_elevation_is_a_shadow_filter_written_from_the_scenes_value(records, exported):
    elevations = set()
    for record in records:
        root = ET.fromstring(exported[record["id"]])
        filters = {node.get("id"): node for node in root.iter(f"{SVG}filter")}
        groups = groups_of(root)
        used = set()
        for element in scene_of(record)["elements"]:
            rect = groups[element["id"]].find(f"{SVG}rect")
            elevation = element["style"]["elevation"]
            if elevation == 0:
                assert rect.get("filter") is None
                continue
            reference = rect.get("filter")
            assert reference.startswith("url(#") and reference.endswith(")")
            shadow = filters[reference[5:-1]]
            used.add(reference[5:-1])
            # The runtime renderer's shadow: the outline moved down by half the
            # elevation, black at alpha 0.24, fading over two elevations.
            assert number(shadow.find(f"{SVG}feGaussianBlur").get("stdDeviation")) == elevation / 2
            assert number(shadow.find(f"{SVG}feOffset").get("dy")) == elevation / 2
            assert float(shadow.find(f"{SVG}feOffset").get("dx", "0")) == 0
            flood = shadow.find(f"{SVG}feFlood")
            assert flood.get("flood-color") == "#000000" and number(flood.get("flood-opacity")) == SHADOW_ALPHA
            elevations.add(elevation)
        assert used == set(filters), "a filter no element uses"
        assert not set(filters) & set(groups), "a filter shares an element's id"
    assert len(elevations) >= 4


def test_text_is_text_in_inter_at_the_scenes_size_and_weight(records, exported):
    multiline = 0
    for record in records:
        root = ET.fromstring(exported[record["id"]])
        groups = groups_of(root)
        for element in scene_of(record)["elements"]:
            texts = groups[element["id"]].findall(f"{SVG}text")
            said = element["bound"]["text"] if element["type"] == "bound" else ""
            if not said:
                assert texts == []
                continue
            assert len(texts) == 1
            text, style = texts[0], element["style"]
            assert text.get("font-family") == "Inter"
            assert number(text.get("font-size")) == style["type_size"]
            assert number(text.get("font-weight")) == style["type_weight"]
            assert text.get("fill") == hex_of(style["text_colour"])
            assert text.get(XML_SPACE) == "preserve"
            lines = said.split("\n")
            if len(lines) == 1:
                assert text.text == said and list(text) == []
            else:
                # One <tspan> for each line that says anything; exact text, nothing between.
                spans = text.findall(f"{SVG}tspan")
                assert text.text is None and [span.text for span in spans] == [line for line in lines if line]
                assert all(span.tail is None for span in spans)
                heights = [number(span.get("y")) for span in spans]
                assert heights == sorted(heights) and len(set(heights)) == len(heights)
                multiline += 1
    assert multiline > 0


def test_text_sits_where_the_runtime_renderer_draws_it(records, exported):
    """Judged by Qt's own font metrics: ascent and descent of the bundled Inter."""
    typography.ensure_gui()
    checked = {"button": 0, "text-area": 0, "other": 0}
    for record in records[::9]:
        groups = groups_of(ET.fromstring(exported[record["id"]]))
        for element in scene_of(record)["elements"]:
            if element["type"] != "bound" or not element["bound"]["text"]:
                continue
            style, box, role = element["style"], element["box"], element["bound"]["role"]
            text = groups[element["id"]].find(f"{SVG}text")
            line = typography.shape("", style["type_weight"])
            ascent = line.ascent * style["type_size"] / 100
            height = (line.ascent + line.descent) * style["type_size"] / 100
            if role == "text-area":
                first = text.find(f"{SVG}tspan") if text.find(f"{SVG}tspan") is not None else text
                assert number(first.get("x")) == pytest.approx(box["x"] + height / 2, abs=1e-4)
                assert number(first.get("y")) == pytest.approx(box["y"] + height / 2 + ascent, abs=1e-4)
                checked["text-area"] += 1
                continue
            assert number(text.get("y")) == pytest.approx(box["y"] + (box["height"] - height) / 2 + ascent, abs=1e-4)
            if role == "button":
                assert text.get("text-anchor") == "middle"
                assert number(text.get("x")) == pytest.approx(box["x"] + box["width"] / 2, abs=1e-4)
                checked["button"] += 1
            else:
                assert text.get("text-anchor") is None
                assert number(text.get("x")) == pytest.approx(box["x"] + max((box["height"] - height) / 2, 0), abs=1e-4)
                checked["other"] += 1
    assert all(checked.values()), checked


