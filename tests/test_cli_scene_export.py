"""Command-line tests for `scene export` and `scene compare` (test seam 2).

`data generate` is run for real on the tiny configuration and `scene export`
is run on the dataset records it wrote. The judge of an SVG is this file: the
SVG is parsed with the standard library's XML parser and compared with the
record's true scene, read from the record's JSON and not through the exporter.
A refusal is compared with the scene session refusing the same scene for the
same application state, reached again here in a kernel of the test's own.
"""

