def scene_of(record: dict) -> dict:
    return record["target"]["scene"]


def groups_of(root: ET.Element) -> dict[str, ET.Element]:
    return {group.get("id"): group for group in root.iter(f"{SVG}g")}


def number(text: str | None) -> float:
    assert text is not None
    return float(text)


def hex_of(colour: list[float]) -> str:
    return "#" + "".join(f"{round(channel * 255):02x}" for channel in colour[:3])


def replay(record: dict):
    """The record's application state, reached again in a kernel of the test's own."""
    kernel = Kernel()
    try:
        for command in record["diagnostics"]["scenario"]["trace"]:
            kernel.execute(command["binding"], command["text"])
        return kernel.state().with_interaction(record["application"]["state"]["interaction"])
    finally:
        kernel.close()


def conditioning_of(record: dict) -> Conditioning:
    viewport = record["inputs"]["viewport"]
    return Conditioning(
        viewport["width"],
        viewport["height"],
        visual_preset=record["diagnostics"]["visual_preset"],
        design_condition=record["inputs"]["design_condition"],
    )


