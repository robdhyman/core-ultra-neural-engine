def test_the_svg_is_one_document_the_size_of_the_viewport(records, exported):
    for record in records:
        root = ET.fromstring(exported[record["id"]])
        viewport = scene_of(record)["viewport"]
        assert root.tag == f"{SVG}svg"
        assert number(root.get("width")) == viewport["width"] and number(root.get("height")) == viewport["height"]
        assert [float(part) for part in root.get("viewBox").split()] == [0, 0, viewport["width"], viewport["height"]]


def test_each_scene_element_is_one_object_carrying_its_id_in_drawing_order(records, exported):
    for record in records:
        root = ET.fromstring(exported[record["id"]])
        elements = scene_of(record)["elements"]
        groups = [group for group in root.iter(f"{SVG}g")]
        # One group for each element and no other: document order is drawing order.
        assert [group.get("id") for group in groups] == [element["id"] for element in elements]
        every_id = [node.get("id") for node in root.iter() if node.get("id") is not None and node.tag != f"{SVG}filter"]
        assert sorted(every_id) == sorted(element["id"] for element in elements)
        for element, group in zip(elements, groups):
            assert group.get("data-type") == element["type"]
            assert group.get("data-role") == (element["bound"]["role"] if element["type"] == "bound" else None)
            # The element's own shape is drawn before anything it contains.
            assert [child.tag for child in group][0] == f"{SVG}rect"
            assert len(group.findall(f"{SVG}rect")) == 1


def test_parent_links_are_groups(records, exported):
    for record in records:
        root = ET.fromstring(exported[record["id"]])
        parent_of = {child.get("id"): parent.get("id") for parent in root.iter(f"{SVG}g") for child in parent.findall(f"{SVG}g")}
        top = [child.get("id") for child in root.findall(f"{SVG}g")]
        elements = scene_of(record)["elements"]
        assert top == [element["id"] for element in elements if element["parent"] is None]
        assert parent_of == {element["id"]: element["parent"] for element in elements if element["parent"] is not None}
        # Siblings keep the order the scene lists them in.
        for element in elements:
            children = [child.get("id") for child in groups_of(root)[element["id"]].findall(f"{SVG}g")]
            assert children == [other["id"] for other in elements if other["parent"] == element["id"]]


