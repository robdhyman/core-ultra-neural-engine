def move_a_box_out_of_the_viewport(record):
    scene_of(record)["elements"][3]["box"]["x"] = 5000.0


def alter_a_bound_elements_text(record):
    bound = next(element for element in scene_of(record)["elements"] if element["type"] == "bound")
    bound["bound"]["text"] = "Something the application never said"


def drop_a_bound_element(record):
    elements = scene_of(record)["elements"]
    elements.remove(next(element for element in elements if element["type"] == "bound"))


def invent_a_bound_element(record):
    elements = scene_of(record)["elements"]
    invented = copy.deepcopy(next(element for element in elements if element["type"] == "bound"))
    invented["id"] = "b.invented"
    invented["bound"]["identity"] = "invented"
    elements.append(invented)


def break_the_tree_and_a_number(record):
    elements = scene_of(record)["elements"]
    elements[2]["parent"] = "s.nowhere"
    elements[4]["style"]["opacity"] = 1.5
    elements[5]["style"]["corner_radius"] = float("nan")


def give_a_structural_element_text(record):
    scene_of(record)["elements"][1]["text"] = "Hello"


BREAKAGES = [
    (move_a_box_out_of_the_viewport, {"outside_viewport"}),
    (alter_a_bound_elements_text, {"bound_altered"}),
    (drop_a_bound_element, {"bound_missing"}),
    (invent_a_bound_element, {"bound_unknown"}),
    (break_the_tree_and_a_number, {"tree", "out_of_range", "non_finite"}),
    (give_a_structural_element_text, {"structural_carries_bound"}),
]


@pytest.mark.parametrize("breakage, codes", BREAKAGES, ids=[breakage.__name__ for breakage, _ in BREAKAGES])
def test_an_invalid_scene_is_refused_with_its_problems_exactly_as_the_scene_session_refuses_it(records, tmp_path, breakage, codes):
    record = copy.deepcopy(records[30])
    breakage(record)
    path = tmp_path / "record.json"
    path.write_text(json.dumps(record))
    out = tmp_path / "refused.svg"

    with pytest.raises(SceneInvalid) as refused:
        SceneSession().frame_from_scene(replay(record), conditioning_of(record), scene_of(record))
    assert refused.value.codes == codes

    result = run_cli("scene", "export", path, "--out", out)
    assert result.returncode == 1
    assert not out.exists() and result.stdout == ""
    listed = [line.removeprefix("  - ") for line in result.stderr.splitlines() if line.startswith("  - ")]
    assert listed == [str(problem) for problem in refused.value.problems]
    assert f"({len(listed)})" in result.stderr.splitlines()[0]


