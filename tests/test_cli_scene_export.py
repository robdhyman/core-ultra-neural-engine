def rasterise(svg: bytes, width: int, height: int) -> np.ndarray:
    """An SVG drawn by Qt's SVG module, by this test and not by the project's code."""
    typography.ensure_gui()
    renderer = QSvgRenderer(QByteArray(svg))
    assert renderer.isValid()
    image = QImage(width, height, QImage.Format.Format_ARGB32_Premultiplied)
    image.fill(QColor(0, 0, 0, 0))
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    renderer.render(painter, QRectF(0, 0, width, height))
    painter.end()
    image = image.convertToFormat(QImage.Format.Format_RGBA8888)
    return np.frombuffer(image.constBits(), dtype=np.uint8).reshape(height, image.bytesPerLine() // 4, 4)[:, :width].copy()


def reference_image(dataset: Path, record: dict) -> np.ndarray:
    image = QImage(str(dataset / record["reference_image"]["file"])).convertToFormat(QImage.Format.Format_RGBA8888)
    width, height = image.width(), image.height()
    return np.frombuffer(image.constBits(), dtype=np.uint8).reshape(height, image.bytesPerLine() // 4, 4)[:, :width].copy()


